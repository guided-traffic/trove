import { Page } from '@playwright/test';
import { e2eProject, expect, expectAccessible, signInLocal, signOut, test } from '../support';

// R-UI-047 journey "ansible documentation" (R-UI-060 to R-UI-064, R-ANS-046): the Documentation, Contents and Import log tabs of a
// collection that ansible-galaxy published into a local repository, and the layout at 1440 and 390 px. Run by TestAnsibleDocsJourney, which publishes the collection and passes its name. The documentation of a
// remote repository's collection is 02-remote.spec.ts.

function env(name: string): string {
  const v = process.env[name];
  if (!v) throw new Error(`${name} is not set: run the journey through TestAnsibleDocsJourney`);
  return v;
}

const local = { name: env('TROVE_E2E_ANSIBLE_DOCS_LOCAL_PACKAGE'), version: env('TROVE_E2E_ANSIBLE_DOCS_LOCAL_VERSION') };

function pageUrl(p: { name: string; version: string }, query = ''): string {
  return `/ui/en/projects/${e2eProject}/packages/ansible/${p.name}?version=${p.version}${query}`;
}

const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: false });
const treeRow = (page: Page, name: RegExp | string) => page.getByRole('treeitem', { name });
const details = (page: Page) => page.locator('.pane-details');

async function bothSchemes(page: Page, screen: string): Promise<void> {
  for (const scheme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: scheme });
    await expectAccessible(page, `${screen} (${scheme})`);
  }
  await page.emulateMedia({ colorScheme: 'light' });
}

test('R-UI-060 R-UI-061 R-UI-062 R-UI-063 R-ANS-046 a collection published with ansible-galaxy: the tree with its counts, the search, the page of a module, Contents and Import log', async ({
  page,
}) => {
  await signInLocal(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(pageUrl(local));

  await test.step('the tabs, and the README as the first page', async () => {
    await expect(tab(page, 'Documentation')).toHaveAttribute('aria-selected', 'true');
    for (const name of ['Contents', 'Metadata', 'Files', 'Repositories', 'All versions', 'Import log']) {
      await expect(tab(page, name).first()).toBeVisible();
    }
    await expect(page.getByRole('tab', { name: 'README' })).toHaveCount(0);
    await expect(details(page)).toContainText(`e2e collection ${local.name}`);
    await expect(treeRow(page, /^Documentation/)).toContainText('2');
    await expect(treeRow(page, /^Modules/)).toContainText('1');
    await expect(page.getByRole('tree', { name: 'Documentation' })).toBeVisible();
    await expect(page.locator('[data-testid="docs-source"]')).toContainText('Generated by trove from the archive');
    await bothSchemes(page, 'documentation tab, README');
  });

  await test.step('the search narrows the tree through the server and keeps the counts', async () => {
    const box = page.getByRole('searchbox', { name: 'Search the documentation' });
    await box.fill('probes');
    await expect(page).toHaveURL(/[?&]q=probes/);
    await expect(page.locator('.match-count')).toHaveText('1 of 1 entries');
    await expect(treeRow(page, /^Modules/)).toContainText('1');
    await expect(treeRow(page, /ping_host/)).toBeVisible();
    await box.fill('nothingmatchesthis');
    await expect(page.getByTestId('docs-no-match')).toContainText('No entries match');
    await box.press('Escape');
    await expect(box).toHaveValue('');
    await expect(page.getByTestId('docs-no-match')).toHaveCount(0);
    await box.fill('probes');
    await expect(treeRow(page, /ping_host/)).toBeVisible();
  });

  await test.step('the page of the module has its parameters, the suboption, the return value and the example', async () => {
    await treeRow(page, /ping_host/).click();
    await expect(page).toHaveURL(/doc=module%2Fping_host/);
    await expect(treeRow(page, /ping_host/)).toHaveAttribute('aria-current', 'page');
    await expect(page.locator('.doc-title')).toContainText(`${local.name}.ping_host`);
    await expect(page.locator('.doc-short')).toContainText('Pings a host of the e2e collection');
    const params = page.getByRole('table', { name: 'Parameters of this entry' });
    for (const name of ['host', 'count', 'proxy', 'url']) {
      await expect(params.locator('th code', { hasText: new RegExp(`^${name}$`) })).toBeVisible();
    }
    await expect(params.locator('tr[data-depth="1"]')).toHaveCount(1);
    await expect(page.getByRole('table', { name: 'Return values of this entry' })).toContainText('rtt');
    await expect(details(page).locator('pre.code-block').first()).toContainText('host: example.com');
    await bothSchemes(page, 'documentation tab, module page');
  });

  await test.step('a reload of the address shows the same page and the same narrowed tree', async () => {
    await page.reload();
    await expect(page.locator('.doc-title')).toContainText(`${local.name}.ping_host`);
    await expect(page.getByRole('searchbox', { name: 'Search the documentation' })).toHaveValue('probes');
    await expect(page.locator('.match-count')).toHaveText('1 of 1 entries');
  });

  await test.step('Contents lists the module with its count in the tab and links to its page', async () => {
    await tab(page, 'Contents').click();
    await expect(tab(page, 'Contents')).toContainText('1');
    const row = page.getByTestId('contents-table').getByRole('row', { name: /ping_host/ });
    await expect(row).toContainText('module');
    await expect(row).toContainText('Pings a host of the e2e collection');
    await bothSchemes(page, 'contents tab');
    await row.getByRole('link', { name: 'ping_host' }).click();
    await expect(tab(page, 'Documentation')).toHaveAttribute('aria-selected', 'true');
    await expect(page.locator('.doc-title')).toContainText(`${local.name}.ping_host`);
  });

  await test.step('Import log shows the import task of the version', async () => {
    await tab(page, 'Import log').click();
    const task = page.locator('section.task').first();
    await expect(task).toContainText('Completed');
    await expect(task.locator('.messages li').first()).toBeVisible();
    await bothSchemes(page, 'import log tab');
  });

  await signOut(page);
});

test('R-UI-060 R-UI-064 the Documentation tab with the install panel above it at 1440 px and on its own at 390 px', async ({ page }, info) => {
  await signInLocal(page);

  await test.step('at 1440 px the tree and the page are side by side, the install panel above them', async () => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto(pageUrl(local, '&doc=module%2Fping_host'));
    await expect(page.locator('.doc-title')).toBeVisible();
    const tree = await page.locator('.pane-tree').boundingBox();
    const body = await page.locator('.pane-details').boundingBox();
    const install = await page.locator('trove-install-panel').boundingBox();
    expect(tree, 'the tree pane is shown').not.toBeNull();
    expect(body, 'the page pane is shown').not.toBeNull();
    expect(install, 'the install panel is shown').not.toBeNull();
    // side by side, the page wide enough to read (more than the tree), nothing wider than the viewport
    expect(body!.x).toBeGreaterThanOrEqual(tree!.x + tree!.width);
    expect(body!.width).toBeGreaterThanOrEqual(tree!.width);
    // the install panel stays above the tabs for this tab, so the page pane has room for the parameter table (Q-UI-257)
    expect(install!.y + install!.height).toBeLessThanOrEqual(tree!.y);
    expect(body!.width).toBeGreaterThan(640);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('docs-1440.png'), fullPage: true });
    info.annotations.push({ type: 'widths', description: `tree ${Math.round(tree!.width)}, page ${Math.round(body!.width)}, install ${Math.round(install!.width)}` });
  });

  await test.step('at 390 px one pane shows at a time, the page does not scroll sideways, and the way back leads to the tree', async () => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(pageUrl(local, '&doc=module%2Fping_host'));
    await expect(page.locator('.doc-title')).toBeVisible();
    await expect(page.locator('.pane-tree')).toBeHidden();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'the page scrolls sideways').toBe(true);
    // the parameter table scrolls inside its own region
    await expect(page.getByRole('region', { name: 'Parameters of this entry' })).toBeVisible();
    await page.screenshot({ path: info.outputPath('docs-390-page.png'), fullPage: true });
    await bothSchemes(page, 'documentation tab at 390 px, module page');
    await page.getByRole('button', { name: /Back to the tree/ }).click();
    await expect(page.locator('.pane-tree')).toBeVisible();
    await expect(page.locator('.pane-details')).toBeHidden();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'the tree scrolls sideways').toBe(true);
    await page.screenshot({ path: info.outputPath('docs-390-tree.png'), fullPage: true });
    await bothSchemes(page, 'documentation tab at 390 px, tree');
  });

  await signOut(page);
});
