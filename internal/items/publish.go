// GeneratedFile is one file of a generation that a format's index build publishes (ADR-170, Q-STOR-182): the file becomes a
// package-less generated item at Path, in a local or a virtual repository.
type GeneratedFile struct {
	Path repository.Cleaned
	// Body is read once; the port spools and hashes it.
	Body      io.Reader
	Size      int64
	MediaType string
	// ModifiedAt is the Release Date for every file of a generation, so that two generations never share a Last-Modified and a
	// client's If-Modified-Since never gets a stale 304 (R-DEB-010).
	ModifiedAt time.Time
}

// Publisher is the publication port of the item store (Q-STOR-182, ADR-170): the one way generated items are written. It is
// implemented here for both classes; a virtual repository accepts generated items from this port and from nothing else (the rule of the
// virtual class, apt-work-packages.md WP8, is checked by the caller that publishes into a virtual repository: this port writes to the
// repository it is given).
type Publisher interface {
	// Publish stores every file's blob first, outside any transaction (R-STOR-005), then runs one transaction that upserts a
	// package-less generated item per file (an identical blob changes nothing but modified_at), deletes the generated items at
	// remove, and runs commit with the transaction for the caller's own rows. commit returning [ErrSuperseded] rolls everything
	// back and Publish returns it; the stored blobs are left to garbage collection. Quota admission does not apply (Q-STOR-181).
	//
	// commit may run more than once (a restarted transaction), like the link function of a commit: it must be safe to run again.
	Publish(ctx context.Context, repo RepoRef, files []GeneratedFile, remove []repository.Cleaned,
		commit func(ctx context.Context, tx meta.Tx) error) error
}

// ErrSuperseded is what the commit function of [Publisher.Publish] returns when a newer build has published already: the
// publication rolls back and returns it.
var ErrSuperseded = errors.New("items: superseded")

// GeneratedItem is the 409 of a client's write, copy, move or delete of an item trove generates from rows (R-STOR-018, Q-STOR-182).
func GeneratedItem() error {
	return errs.E(errs.Conflict, errs.CodeGeneratedItem, "The item is generated by trove from the repository's rows; a client neither writes nor deletes it.")
}

// maxPublishFiles bounds the files of one generation: a Debian suite publishes a few hundred indexes and their by-hash copies.
const maxPublishFiles = 20000

// Publish implements [Publisher] (Q-STOR-182). The blobs go to the object store by the commit protocol of every other write
// (blob.CommitAll: objects first, then one link transaction that holds the share lock of every blob row), and the link function is
// the publication: ancestor folders, one generated item per file, the removals, and the caller's own writes. Nothing in it is audited
// or handed to a storage hook: a generation is not a client's write, and a hook would see its own index files as uploads.
//
// An identical file at a path changes nothing but modified_at; a path that holds a client's file or other generated content takes
// the new content and becomes generated. A path in remove that holds a client's file is left alone.
func (s *Store) Publish(ctx context.Context, repo RepoRef, files []GeneratedFile, remove []repository.Cleaned,
	commit func(ctx context.Context, tx meta.Tx) error,
) error {
	if err := checkPublishTarget(repo); err != nil {
		return err
	}
	if err := checkPublication(files, remove); err != nil {
		return err
	}
	spooled := make([]*Spooled, 0, len(files))
	defer func() {
		for _, sp := range spooled {
			_ = sp.Close()
		}
	}()
	for _, f := range files {
		sp, err := s.Spool(ctx, f.Body, IngestOptions{ContentLength: f.Size, MaxSize: f.Size})
		if err != nil {
			return err
		}
		spooled = append(spooled, sp)
	}
	link := func(ctx context.Context, tx meta.Tx) error {
		qs, err := queries(tx)
		if err != nil {
			return err
		}
		for i, f := range files {
			if err := linkGenerated(ctx, qs, repo, f, spooled[i]); err != nil {
				return err
			}
		}
		for _, p := range remove {
			ids, err := qs.DeleteGeneratedItem(ctx, q.DeleteGeneratedItemParams{RepoID: repo.ID, Path: p.Path})
			if err != nil {
				return err
			}
			if len(ids) > 0 {
				if err := s.sweepAncestors(ctx, tx, qs, repo.ID, ParentOf(p.Path)); err != nil {
					return err
				}
			}
		}
		if commit == nil {
			return nil
		}
		return commit(ctx, tx)
	}
	var err error
	if len(spooled) == 0 {
		// No blob to store: only the removals and the caller's rows.
		err = s.run.InTx(ctx, func(tx meta.Tx) error { return link(ctx, tx) })
	} else {
		_, err = s.blobs.CommitAll(ctx, spooled, link)
	}
	if err != nil {
		return err
	}
	s.touch(repo.ID)
	return nil
}

func checkPublication(files []GeneratedFile, remove []repository.Cleaned) error {
	if len(files) > maxPublishFiles || len(remove) > maxPublishFiles {
		return errs.E(errs.Internal, errs.CodeInternal, "items: a generation has too many files")
	}
	seen := make(map[string]bool, len(files)+len(remove))
	for _, f := range files {
		switch {
		case f.Path.Path == "" || f.Path.Folder:
			return errs.E(errs.Invalid, errs.CodeInvalidPath, "A generated file is published at a path that names a file.")
		case f.Body == nil || f.Size < 0:
			return errs.E(errs.Internal, errs.CodeInternal, "items: a generated file has no body")
		case seen[f.Path.Path]:
			return errs.E(errs.Internal, errs.CodeInternal, "items: two generated files take the path "+f.Path.Path)
		}
		seen[f.Path.Path] = true
	}
	for _, p := range remove {
		switch {
		case p.Path == "" || p.Folder:
			return errs.E(errs.Invalid, errs.CodeInvalidPath, "A generated file is removed by a path that names a file.")
		case seen[p.Path]:
			return errs.E(errs.Internal, errs.CodeInternal, "items: the path "+p.Path+" is both published and removed")
		}
		seen[p.Path] = true
	}
	return nil
}

// linkGenerated writes one generated file in the transaction that holds the blob row's lock: the ancestor folders, then the item row.
// It may run again, and resets nothing it keeps.
func linkGenerated(ctx context.Context, qs *q.Queries, repo RepoRef, f GeneratedFile, sp *Spooled) error {
	path := f.Path.Path
	p := fileParams{rid: repo.ID, path: path, parent: ParentOf(path), spec: CommitSpec{
		Spooled: sp, MediaType: f.MediaType, generated: true,
	}}
	modified := ""
	if !f.ModifiedAt.IsZero() {
		modified = f.ModifiedAt.UTC().Format(time.RFC3339Nano)
	}
	p.modified = modified
	for range maxLinkRounds {
		if err := ensureParents(ctx, qs, repo.ID, "", path); err != nil {
			return err
		}
		locked, err := lockAncestors(ctx, qs, repo.ID, path)
		if err != nil {
			return err
		}
		if !locked {
			continue
		}
		rows, err := qs.LockLiveItem(ctx, q.LockLiveItemParams{RepoID: repo.ID, Path: path})
		if err != nil {
			return err
		}
		switch {
		case len(rows) == 0:
			if _, ok, err := insertFile(ctx, qs, p); err != nil {
				return err
			} else if !ok {
				continue // a concurrent writer took the path: lock it and replace
			}
			return nil
		case rows[0].Kind != KindFile:
			return PathConflict("the path is a folder")
		case bytes.Equal(rows[0].BlobSha256, sp.SHA256[:]):
			_, err := qs.TouchGeneratedItem(ctx, q.TouchGeneratedItemParams{ID: rows[0].ID, ModifiedAt: orNow(modified)})
			return err
		default:
			return replaceFile(ctx, qs, rows[0].ID, p)
		}
	}
	return errs.E(errs.Unavailable, errs.CodeUnavailable, "The path is being changed by concurrent requests; retry.", errs.WithRetryAfter(retryAfter))
}

// orNow is the time a statement casts: the caller's, or the transaction's start when it gave none.
func orNow(modified string) string {
	if modified != "" {
		return modified
	}
	return time.Now().UTC().Format(time.RFC3339Nano)
}

var _ Publisher = (*Store)(nil)
