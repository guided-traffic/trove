var updateSnippetIDs = flag.Bool("update-snippet-ids", false, "rewrite web/src/app/features/setup/snippet-ids.fixture.ts")

const snippetIDsFixture = "../../../web/src/app/features/setup/snippet-ids.fixture.ts"

// renderedSnippetIDs renders every client of a format's templates, for a caller who may publish, with the scope given (only npm has scopes, so only its call gives one), and returns the sorted
// ids the API sends (snippetID, Q-API-160), per client.
func renderedSnippetIDs(t *testing.T, scope string, f interface {
	SetupTemplates() []formats.SetupTemplate
},
) map[string][]string {
	t.Helper()
	tpls := f.SetupTemplates()
	out := map[string][]string{}
	for _, tpl := range tpls {
		if _, ok := out[tpl.Client]; ok {
			continue
		}
		var ids []string
		for _, cred := range []string{credPlaceholder, credNone} {
			ss, err := renderSnippets(setupInput{
				Templates: tpls, Client: tpl.Client, Credentials: cred, TokenEnvVar: "TROVE_TOKEN", MayPublish: true, Scope: scope,
				Data: formats.SetupData{
					RegistryURL: "https://trove.example.net/x/", ImagePrefix: "trove.example.net/web/x", Repository: "x", Endpoint: "default",
					RequiresAuth: true, Username: "alice",
				},
			})
			if err != nil {
				t.Fatal(err)
			}
			for _, s := range ss {
				if !slices.Contains(ids, s.ID) {
					ids = append(ids, s.ID)
				}
			}
		}
		slices.Sort(ids)
		out[tpl.Client] = ids
	}
	return out
}

func renderIDsFixture(t *testing.T) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("// Generated by TestR_API_030_RenderedSnippetIdsMatchTheUIFixture (internal/api/v1/setup_snippet_ids_test.go);\n")
	b.WriteString("// regenerate with: go test ./internal/api/v1 -run RenderedSnippetIds -update-snippet-ids\n")
	b.WriteString("// The ids the API sends for every client of a format (<client>.<section>[.<name>], Q-API-160); a UI spec checks that each has an explanation.\n")
	b.WriteString("export const RENDERED_SNIPPET_IDS: Readonly<Record<string, readonly string[]>> = {\n")
	for _, fm := range []struct {
		name, scope string
		f           interface {
			SetupTemplates() []formats.SetupTemplate
		}
	}{{"generic", "", generic.Format{}}, {"npm", "acme", &npm.Format{}}, {"nuget", "", &nuget.Format{}}, {"oci", "", &oci.Format{}}} {
		ids := renderedSnippetIDs(t, fm.scope, fm.f)
		clients := make([]string, 0, len(ids))
		for c := range ids {
			clients = append(clients, c)
		}
		slices.Sort(clients)
		for _, c := range clients {
			b.WriteString("  '" + fm.name + ":" + c + "': [\n")
			for _, id := range ids[c] {
				b.WriteString("    '" + id + "',\n")
			}
			b.WriteString("  ],\n")
		}
	}
	b.WriteString("};\n")
	return b.String()
}

func TestR_API_030_RenderedSnippetIdsMatchTheUIFixture(t *testing.T) {
	want := renderIDsFixture(t)
	path := filepath.FromSlash(snippetIDsFixture)
	if *updateSnippetIDs {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale: the rendered snippet ids changed; run go test ./internal/api/v1 -run RenderedSnippetIds -update-snippet-ids", snippetIDsFixture)
	}
}
