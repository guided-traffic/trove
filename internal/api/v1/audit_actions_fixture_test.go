package v1

import (
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/guided-traffic/trove/internal/audit"
)

var updateAuditActions = flag.Bool("update-audit-actions", false, "rewrite web/src/app/features/audit/audit-actions.fixture.ts")

const auditActionsFixture = "../../../web/src/app/features/audit/audit-actions.fixture.ts"

// renderAuditActionsFixture lists every event type of the audit registry (R-OPS-014), sorted by name, for the UI: the action
// filter of the audit log suggests its types and their prefixes, and audit-labels.spec.ts walks it, so that each type has a plain
// name (R-UI-037).
func renderAuditActionsFixture() string {
	var b strings.Builder
	b.WriteString("// Generated by TestR_UI_037_EveryAuditEventTypeIsInTheUIFixture (internal/api/v1/audit_actions_fixture_test.go);\n")
	b.WriteString("// regenerate with: go test ./internal/api/v1 -run EveryAuditEventType -update-audit-actions\n")
	b.WriteString("// Every event type of the audit registry (internal/audit): the action filter suggests them and their prefixes, and a UI spec\n")
	b.WriteString("// checks that each has a plain name (R-UI-037).\n")
	b.WriteString("export const REGISTERED_AUDIT_ACTIONS: readonly string[] = [\n")
	for _, t := range audit.Types() {
		b.WriteString("  '" + t.Name + "',\n")
	}
	b.WriteString("];\n")
	return b.String()
}

func TestR_UI_037_EveryAuditEventTypeIsInTheUIFixture(t *testing.T) {
	want := renderAuditActionsFixture()
	path := filepath.FromSlash(auditActionsFixture)
	if *updateAuditActions {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale: the audit registry changed; run go test ./internal/api/v1 -run EveryAuditEventType -update-audit-actions", auditActionsFixture)
	}
}
