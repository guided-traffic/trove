// Command schemagen writes the JSON Schema of the configuration tree and the files the chart
// trove-bastion derives from the schema of the role bastion. It is run by `go generate ./internal/config`.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/guided-traffic/trove/internal/config"
)

// The files of the chart trove-bastion that are generated from bastion.schema.json (R-BAS-046, Q-BAS-58).
const (
	chartSchemaFile  = "values.schema.json"
	chartManagedFile = "chart-managed-keys.yaml"
)

func main() {
	out := flag.String("out", "schema.json", "output file of the main configuration tree")
	bastionOut := flag.String("bastion-out", "", "output file of the role bastion's tree (empty: not written)")
	bastionChart := flag.String("bastion-chart", "", "directory of the chart trove-bastion whose config schema and managed-key list are written from the role's tree (empty: not written)")
	flag.Parse()
	write(*out, config.MustDescribe().JSONSchema)
	if *bastionOut != "" {
		write(*bastionOut, config.BastionDescribe().BastionJSONSchema)
	}
	if *bastionChart != "" {
		b, err := config.BastionDescribe().BastionJSONSchema()
		if err != nil {
			fail(err)
		}
		if err := writeChart(*bastionChart, b); err != nil {
			fail(err)
		}
	}
}

func write(path string, render func() ([]byte, error)) {
	b, err := render()
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(path, append(b, '\n'), 0o600); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "schemagen:", err)
	os.Exit(1)
}

// writeChart replaces the value of properties.config in the chart's values.schema.json with the role schema
// (without $schema and $id: the root of the chart's schema is draft-07) and writes the keys the chart renders
// itself, which the chart refuses under config, next to it.
func writeChart(dir string, role []byte) error {
	var roleTree map[string]any
	if err := json.Unmarshal(role, &roleTree); err != nil {
		return fmt.Errorf("role schema: %w", err)
	}
	delete(roleTree, "$schema")
	delete(roleTree, "$id")
	path := filepath.Join(dir, chartSchemaFile)
	raw, err := os.ReadFile(path) //nolint:gosec // the path is the generator's own flag
	if err != nil {
		return err
	}
	rendered, err := spliceConfig(raw, roleTree)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if err := os.WriteFile(path, rendered, 0o644); err != nil { //nolint:gosec // a chart file, read by helm
		return err
	}
	paths := managedRoots(roleTree, "")
	sort.Strings(paths)
	var list bytes.Buffer
	list.WriteString("# Generated by go generate ./internal/config from the chart-managed keys of internal/config/bastion.schema.json; do not edit.\n")
	list.WriteString("# The chart renders these keys of config itself and refuses a value for them (templates/_validate.tpl).\n")
	for _, p := range paths {
		fmt.Fprintf(&list, "- %s\n", p)
	}
	return os.WriteFile(filepath.Join(dir, chartManagedFile), list.Bytes(), 0o644) //nolint:gosec // a chart file, read by helm
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// managedRoots lists the topmost paths whose whole subtree is chart-managed: a marked node, or an object all
// of whose properties are managed (server.tls, not each of its keys).
func managedRoots(node map[string]any, path string) []string {
	props, _ := node["properties"].(map[string]any)
	var out []string
	for name, v := range props {
		child, ok := v.(map[string]any)
		if !ok {
			continue
		}
		p := name
		if path != "" {
			p = path + "." + name
		}
		if allManaged(child) {
			out = append(out, p)
			continue
		}
		out = append(out, managedRoots(child, p)...)
	}
	return out
}

func allManaged(node map[string]any) bool {
	if marked, _ := node["x-trove-chart-managed"].(bool); marked {
		return true
	}
	props, _ := node["properties"].(map[string]any)
	if len(props) == 0 {
		return false
	}
	for _, v := range props {
		child, ok := v.(map[string]any)
		if !ok || !allManaged(child) {
			return false
		}
	}
	return true
}

// configKey is the line that starts the config property inside "properties" of the chart's schema, which is
// indented by two levels.
const configKey = "\n    \"config\": "

// spliceConfig replaces the value of properties.config in the text of the chart's schema and leaves every
// other byte as it is, so that the hand-written part keeps its order.
func spliceConfig(raw []byte, role map[string]any) ([]byte, error) {
	start := bytes.Index(raw, []byte(configKey))
	if start < 0 || bytes.Contains(raw[start+1:], []byte(configKey)) {
		return nil, fmt.Errorf("want exactly one property config at the second level")
	}
	start += len(configKey)
	dec := json.NewDecoder(bytes.NewReader(raw[start:]))
	var old json.RawMessage
	if err := dec.Decode(&old); err != nil {
		return nil, fmt.Errorf("config: %w", err)
	}
	end := start + int(dec.InputOffset())
	body, err := marshal(role)
	if err != nil {
		return nil, err
	}
	body = bytes.ReplaceAll(bytes.TrimRight(body, "\n"), []byte("\n"), []byte("\n    "))
	out := append([]byte{}, raw[:start]...)
	out = append(out, body...)
	return append(out, raw[end:]...), nil
}
