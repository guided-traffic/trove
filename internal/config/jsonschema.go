package config

import (
	"encoding/json"
	"reflect"
	"strings"
)

// SchemaID identifies the generated JSON Schema.
const SchemaID = "https://github.com/guided-traffic/trove/internal/config/schema.json"

// JSONSchema renders the configuration tree as a JSON Schema (draft 2020-12)
// for the chart's values validation and for editors. It is generated from the
// same tags the loader reads, so the two cannot drift; the output is stable
// (object keys sort) and committed as schema.json.
func (s *Schema) JSONSchema() ([]byte, error) {
	root := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"$id":                  SchemaID,
		"title":                "trove configuration",
		"description":          "Generated by go generate ./internal/config from the struct tree; do not edit.",
		"type":                 "object",
		"additionalProperties": false,
		"properties":           map[string]any{},
	}
	for _, k := range s.Keys {
		parts := strings.Split(k.Path, ".")
		node := root
		for _, p := range parts[:len(parts)-1] {
			props := node["properties"].(map[string]any)
			child, ok := props[p].(map[string]any)
			if !ok {
				child = map[string]any{"type": "object", "additionalProperties": false, "properties": map[string]any{}}
				props[p] = child
			}
			node = child
		}
		leaf := parts[len(parts)-1]
		node["properties"].(map[string]any)[leaf] = k.schemaNode()
		if k.Required {
			req, _ := node["required"].([]string)
			node["required"] = append(req, leaf)
		}
	}
	return json.MarshalIndent(root, "", "  ")
}

func (k Key) schemaNode() map[string]any {
	n := map[string]any{"x-trove-env": k.Env}
	if k.Doc != "" {
		n["description"] = k.Doc
	}
	switch k.Kind {
	case KindSecretValue:
		n["x-trove-secret"] = "env-only"
	case KindSecretFile:
		n["x-trove-secret"] = "file"
	case KindSecretFileOnly:
		n["x-trove-secret"] = "file-only"
	}
	t := k.Type
	switch t {
	case durTyp:
		n["type"] = "string"
		n["pattern"] = `^[0-9]+(\.[0-9]+)?(ns|us|µs|ms|s|m|h)([0-9]+(\.[0-9]+)?(ns|us|µs|ms|s|m|h))*$|^0$`
		n["x-trove-type"] = "duration"
	case sizeTyp:
		n["type"] = []string{"string", "integer"}
		n["x-trove-type"] = "bytes"
	default:
		switch t.Kind() {
		case reflect.String:
			n["type"] = "string"
		case reflect.Bool:
			n["type"] = "boolean"
		case reflect.Int, reflect.Int32, reflect.Int64:
			n["type"] = "integer"
		case reflect.Float64:
			n["type"] = "number"
		case reflect.Slice:
			n["type"] = "array"
			n["items"] = map[string]any{"type": "string"}
			if isStructList(t) {
				n["items"] = elementSchema(t.Elem())
			}
		case reflect.Map:
			n["type"] = "object"
		}
	}
	if k.HasDefault && k.Kind != KindSecretValue {
		if v, err := parseText(t, k.Default); err == nil {
			n["default"] = displayValue(v)
		}
	}
	for _, r := range k.Rules {
		switch r.op {
		case "oneof":
			n["enum"] = r.oneof
		case "min", "max":
			applyBound(n, k.Type, r)
		}
	}
	return n
}

func applyBound(n map[string]any, t reflect.Type, r rule) {
	if t == durTyp || t == sizeTyp {
		return // text forms; the loader enforces the bound
	}
	var lo, hi string
	switch t.Kind() {
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Float64:
		lo, hi = "minimum", "maximum"
	case reflect.String:
		lo, hi = "minLength", "maxLength"
	case reflect.Slice:
		lo, hi = "minItems", "maxItems"
	default:
		return
	}
	key := lo
	if r.op == "max" {
		key = hi
	}
	if t.Kind() == reflect.Float64 || r.num == float64(int64(r.num)) {
		if t.Kind() == reflect.Float64 {
			n[key] = r.num
		} else {
			n[key] = int64(r.num)
		}
	}
}

// elementSchema describes the struct element of a list: a closed object of its
// scalar fields, the ones tagged required listed as such.
func elementSchema(t reflect.Type) map[string]any {
	props := map[string]any{}
	var required []string
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name, _, _ := strings.Cut(f.Tag.Get("yaml"), ",")
		p := map[string]any{}
		switch f.Type.Kind() {
		case reflect.String:
			p["type"] = "string"
		case reflect.Bool:
			p["type"] = "boolean"
		case reflect.Int, reflect.Int32, reflect.Int64:
			p["type"] = "integer"
		case reflect.Float64:
			p["type"] = "number"
		}
		if d := f.Tag.Get("doc"); d != "" {
			p["description"] = d
		}
		if f.Tag.Get("secret") == "file" {
			p["x-trove-secret"] = "file-only"
		}
		if strings.Contains(","+f.Tag.Get("validate")+",", ",required,") {
			required = append(required, name)
			p["minLength"] = 1
		}
		props[name] = p
	}
	out := map[string]any{"type": "object", "additionalProperties": false, "properties": props}
	if len(required) > 0 {
		out["required"] = required
	}
	return out
}
