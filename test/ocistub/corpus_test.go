// Two builds of the corpus, and two servers, serve identical digests: nothing in the set depends on a clock, a random source or
// map order .
func TestCorpusIsDeterministic(t *testing.T) {
	a, b := Default(), Default()
	if !slices.Equal(a.Names(), b.Names()) {
		t.Fatalf("names differ: %v vs %v", a.Names(), b.Names())
	}
	for _, name := range a.Names() {
		if !maps.Equal(a.repos[name].tags, b.repos[name].tags) {
			t.Errorf("%s: tags differ between two builds", name)
		}
	}
	if len(a.blobs) != len(b.blobs) || len(a.manifests) != len(b.manifests) {
		t.Fatalf("object counts differ: %d/%d blobs, %d/%d manifests", len(a.blobs), len(b.blobs), len(a.manifests), len(b.manifests))
	}
	for d, data := range a.blobs {
		if !bytes.Equal(data, b.blobs[d]) {
			t.Errorf("blob %s differs between two builds", d)
		}
	}

	s1, err := New(Config{Corpus: Default()})
	if err != nil {
		t.Fatal(err)
	}
	s2, err := New(Config{Corpus: Default()})
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range s1.Repositories() {
		t1, _ := s1.Tags(name)
		t2, _ := s2.Tags(name)
		if !maps.Equal(t1, t2) {
			t.Errorf("%s: two servers serve different digests", name)
		}
	}
}

// The digests below are pinned so that an unintended change of the generated bytes shows in review; the change that moves them on
// purpose (a new layer size, another field) updates the constants. They are what the generator produces with the Go release the
// repository pins, which the tar and gzip writers do not make depend on.
func TestCorpusPinnedDigests(t *testing.T) {
	pins := []struct{ name, tag, digest string }{
		{"library/alpine", "3", "sha256:e5a7e9d01a8e098d991c3b53b9dfd163b2effb651ae189f80b053c3e28736750"},
		{"acme/a", "1.0", "sha256:98e001196cc82e38ef92c28baec9818948f21db1e0c1540f7d3869c3edcfd683"},
		{"bulk/tags", "t0001", "sha256:8556bd32ac24e3c46796c81a49345e5ebc5928c6c9696fe905af9e518d905db2"},
	}
	c := Default()
	for _, p := range pins {
		if got, _ := c.Digest(p.name, p.tag); got != p.digest {
			t.Errorf("%s:%s = %s, pinned %s", p.name, p.tag, got, p.digest)
		}
	}
}

func TestCorpusContent(t *testing.T) {
	c := Default()
	wantRepos := []string{"acme/a", "acme/b", "acme/signed", "acme/tool", "app", "bulk/tags", "library/alpine", "library/app", "library/busybox", "library/nginx", "other/c"}
	if got := c.Names(); !slices.Equal(got, wantRepos) {
		t.Fatalf("repositories = %v, want %v", got, wantRepos)
	}
	if n := len(c.repos[BulkRepository].tags); n != BulkTags {
		t.Errorf("%s has %d tags, want %d", BulkRepository, n, BulkTags)
	}
	if got := len(c.repos["acme/a"].tags); got != 5 {
		t.Errorf("acme/a has %d tags, want 5", got)
	}
	// Five distinct images in acme/a.
	seen := map[string]bool{}
	for _, d := range c.repos["acme/a"].tags {
		seen[d] = true
	}
	if len(seen) != 5 {
		t.Errorf("acme/a tags share manifests: %d distinct digests, want 5", len(seen))
	}

	// Every manifest names only content its repository holds, and every stored blob has the digest it is stored under.
	for name, r := range c.repos {
		for d := range r.members {
			if o := c.manifests[d]; o != nil {
				if sha(o.data) != d {
					t.Errorf("%s: manifest %s is stored under another digest", name, d)
				}
				var doc manifestDoc
				if err := json.Unmarshal(o.data, &doc); err != nil {
					t.Fatalf("%s %s: %v", name, d, err)
				}
				for _, ref := range descriptors(doc) {
					if !r.members[ref.Digest] {
						t.Errorf("%s: %s names %s, which the repository does not hold", name, d, ref.Digest)
					}
				}
			} else if data, ok := c.blobs[d]; !ok || sha(data) != d {
				t.Errorf("%s: member %s is neither a manifest nor a blob with its digest", name, d)
			}
		}
	}
}

func descriptors(doc manifestDoc) []Descriptor {
	var out []Descriptor
	if doc.Config != nil {
		out = append(out, *doc.Config)
	}
	out = append(out, doc.Layers...)
	out = append(out, doc.Manifests...)
	if doc.Subject != nil {
		out = append(out, *doc.Subject)
	}
	return out
}

func TestImageShapes(t *testing.T) {
	s, err := New(Config{})
	if err != nil {
		t.Fatal(err)
	}
	cases := []struct {
		name, tag, mediaType string
		children             int
		platforms            []string
		attestations         int
		layerType            string
	}{
		{"library/busybox", "latest", MediaDockerList, 2, []string{"linux/amd64", "linux/arm64/v8"}, 0, MediaDockerLayer},
		{"library/busybox", "1.35", MediaDockerManifest, 0, nil, 0, MediaDockerLayer},
		{"library/alpine", "3", MediaOCIIndex, 4, []string{"linux/amd64", "linux/arm64/v8"}, 2, MediaOCILayer},
		{"library/alpine", "3.19", MediaOCIManifest, 0, nil, 0, MediaOCILayer},
		{"acme/b", "latest", MediaOCIIndex, 4, []string{"linux/amd64", "linux/arm64/v8"}, 2, MediaOCILayer},
		{"library/nginx", "1", MediaDockerList, 2, []string{"linux/amd64", "linux/arm64/v8"}, 0, MediaDockerLayer},
	}
	for _, tc := range cases {
		t.Run(tc.name+":"+tc.tag, func(t *testing.T) {
			info, err := s.Image(tc.name, tc.tag)
			if err != nil {
				t.Fatal(err)
			}
			if info.MediaType != tc.mediaType || len(info.Manifests) != tc.children {
				t.Fatalf("media type %s with %d manifests, want %s with %d", info.MediaType, len(info.Manifests), tc.mediaType, tc.children)
			}
			var platforms []string
			attestations := 0
			for _, m := range info.Manifests {
				if m.AttestationFor != "" {
					attestations++
					if m.Platform != "unknown/unknown" || len(m.Layers) != 1 || m.Layers[0].MediaType != MediaInToto {
						t.Errorf("attestation manifest %+v is not BuildKit's shape", m)
					}
					if _, ok := info.ForPlatform("linux/amd64"); !ok {
						t.Error("no linux/amd64 manifest")
					}
					continue
				}
				platforms = append(platforms, m.Platform)
				if m.Layers[0].MediaType != tc.layerType {
					t.Errorf("layer media type %s, want %s", m.Layers[0].MediaType, tc.layerType)
				}
			}
			if !slices.Equal(platforms, tc.platforms) || attestations != tc.attestations {
				t.Errorf("platforms %v and %d attestations, want %v and %d", platforms, attestations, tc.platforms, tc.attestations)
			}
			if tc.children == 0 && (info.Config == nil || len(info.Layers) != 2 || info.Layers[0].MediaType != tc.layerType) {
				t.Errorf("single image has config %v and layers %v", info.Config, info.Layers)
			}
		})
	}
}

// An attestation entry names the platform manifest it is about.
func TestAttestationNamesItsChild(t *testing.T) {
	s, _ := New(Config{})
	info, err := s.Image("library/alpine", "latest")
	if err != nil {
		t.Fatal(err)
	}
	children := map[string]bool{}
	for _, m := range info.Manifests {
		if m.AttestationFor == "" {
			children[m.Digest] = true
		}
	}
	for _, m := range info.Manifests {
		if m.AttestationFor != "" && !children[m.AttestationFor] {
			t.Errorf("attestation %s is for %s, which is no manifest of the index", m.Digest, m.AttestationFor)
		}
	}
}

// A configuration's diff IDs are the digests of the uncompressed layers, so a runtime that unpacks the layers is satisfied.
func TestLayersAreRealTarballs(t *testing.T) {
	c := Default()
	digest, _ := c.Digest("acme/a", "1.0")
	var m imageManifest
	if err := json.Unmarshal(c.manifests[digest].data, &m); err != nil {
		t.Fatal(err)
	}
	var cfg struct {
		RootFS struct {
			DiffIDs []string `json:"diff_ids"`
		} `json:"rootfs"`
	}
	if err := json.Unmarshal(c.blobs[m.Config.Digest], &cfg); err != nil {
		t.Fatal(err)
	}
	if len(cfg.RootFS.DiffIDs) != len(m.Layers) {
		t.Fatalf("%d diff IDs for %d layers", len(cfg.RootFS.DiffIDs), len(m.Layers))
	}
	for i, l := range m.Layers {
		zr, err := gzip.NewReader(bytes.NewReader(c.blobs[l.Digest]))
		if err != nil {
			t.Fatal(err)
		}
		raw, err := io.ReadAll(zr)
		if err != nil {
			t.Fatal(err)
		}
		if sha(raw) != cfg.RootFS.DiffIDs[i] {
			t.Errorf("layer %d: diff ID %s, uncompressed digest %s", i, cfg.RootFS.DiffIDs[i], sha(raw))
		}
		if _, err := tar.NewReader(bytes.NewReader(raw)).Next(); err != nil {
			t.Errorf("layer %d is no tar archive: %v", i, err)
		}
		if int64(len(c.blobs[l.Digest])) != l.Size {
			t.Errorf("layer %d: size %d announced, %d stored", i, l.Size, len(c.blobs[l.Digest]))
		}
	}
}

func TestReferrersOfSignedImage(t *testing.T) {
	c := Default()
	subject, _ := c.Digest("acme/signed", "1.0")
	idx := c.referrersIndex(c.repos["acme/signed"], subject, "")
	var doc indexManifest
	if err := json.Unmarshal(idx.data, &doc); err != nil {
		t.Fatal(err)
	}
	var types []string
	for _, d := range doc.Manifests {
		types = append(types, d.ArtifactType)
	}
	if !slices.Equal(types, []string{ArtifactSignature, ArtifactSBOM}) {
		t.Fatalf("referrers artifact types = %v", types)
	}
	if fb, ok := c.Digest("acme/signed", FallbackTag(subject)); !ok || fb != idx.digest {
		t.Errorf("the tag schema fallback tag points at %q, want the referrers index %s", fb, idx.digest)
	}
	var filtered indexManifest
	if err := json.Unmarshal(c.referrersIndex(c.repos["acme/signed"], subject, ArtifactSBOM).data, &filtered); err != nil {
		t.Fatal(err)
	}
	if len(filtered.Manifests) != 1 || filtered.Manifests[0].ArtifactType != ArtifactSBOM {
		t.Errorf("filtered referrers = %+v", filtered.Manifests)
	}
	// The referrer names its subject.
	var ref imageManifest
	if err := json.Unmarshal(c.manifests[doc.Manifests[0].Digest].data, &ref); err != nil {
		t.Fatal(err)
	}
	if ref.Subject == nil || ref.Subject.Digest != subject {
		t.Errorf("referrer subject = %+v, want %s", ref.Subject, subject)
	}
}
